/**
 * Настройки карты, которые собирает панель слева. Кроме формы графа сюда входят значения физики —
 * они доезжают до `ForceGraph` и применяются к уже собранной сцене без её пересборки.
 */
export type GraphSettings = {
	/** Во сколько раз клонировать граф: каждая копия — полная копия всех узлов и связей. */
	nodeClones: number
	/** Полный вид саб нод: раскрывать иконки патентов целиком, а не значком. */
	showFullSubNodes: boolean
	/** Скрыть саб ноды: не рисовать патенты на карте. */
	hideSubNodes: boolean
	/** Растяжка раскладки: простор между несвязанными узлами. */
	layoutScale: number
	/** Дистанция покоя связи: плотность связок внутри кластера. */
	linkDistance: number
	/** Крепость связи, плоская для всех связей. */
	linkStrength: number
	/** Сила заряда (отталкивания); отрицательная — узлы расталкиваются. */
	chargeStrength: number
	/** Доля скорости, теряемая за тик: выше — карта останавливается быстрее. */
	velocityDecay: number
	/** Разогрев при перетаскивании узла: меньше значение — меньше едет остальная карта. */
	dragAlphaTarget: number
	/** Разогрев после обновления данных. */
	updateAlpha: number
}
