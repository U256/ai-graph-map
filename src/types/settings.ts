/**
 * Настройки карты, которые собирает панель слева: сабмит формы отдаёт их наверх, `App` держит их в
 * стейте и передаёт карте. Пока это только транспорт — сцена значения не читает.
 */
export type GraphSettings = {
	/** Мультипликатор нод: во сколько раз увеличивать узлы на сцене. */
	nodeMultiplier: number
	/** Полный вид саб нод: раскрывать иконки патентов целиком, а не значком. */
	showFullSubNodes: boolean
	/** Скрыть саб ноды: не рисовать патенты на карте. */
	hideSubNodes: boolean
}
